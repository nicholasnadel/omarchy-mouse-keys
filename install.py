#!/usr/bin/env python3
"""Install a device-scoped Kanata mouse-key layer on Omarchy."""

import argparse
import os
from pathlib import Path
import pwd
import shutil
import subprocess
import sys
import tempfile


ROOT = Path(__file__).resolve().parent
HOME = Path.home()
CONFIG = HOME / ".config/kanata/mouse-keys.kbd"
SERVICE = HOME / ".config/systemd/user/kanata-mouse-keys.service"
RULE = Path("/etc/udev/rules.d/90-kanata-mouse-keys-uaccess.rules")
BINARY = HOME / ".local/bin/kanata"
VERSION = "1.12.0"
COMMIT = "02242ef761ef43b860eac30067ce86904be7d466"


def run(*args, **kwargs):
    return subprocess.run(args, check=True, **kwargs)


def keyboard_devices():
    """Return exact kernel names and event nodes for connected keyboards."""
    devices = {}
    for sys_device in sorted(Path("/sys/class/input").glob("event*")):
        node = Path("/dev/input") / sys_device.name
        name_file = sys_device / "device/name"
        if not name_file.exists() or not node.exists():
            continue
        properties = subprocess.run(
            ["udevadm", "info", "--query=property", "--name", str(node)],
            capture_output=True,
            text=True,
            check=False,
        )
        if "ID_INPUT_KEYBOARD=1" not in properties.stdout.splitlines():
            continue
        name = name_file.read_text().strip()
        if name.casefold().startswith("kanata"):
            continue
        devices.setdefault(name, []).append(node)
    return devices


def validate_names(names):
    for name in names:
        # udev matches ATTRS values as patterns, so reject glob characters too.
        if not name or any(ch in name for ch in ('"', "\\", "\n", "\r", "*", "?", "[", "]")):
            raise ValueError(f"Unsupported device name: {name!r}")
        if any(ord(ch) < 32 for ch in name):
            raise ValueError(f"Unsupported control character in device name: {name!r}")


def render(names):
    validate_names(names)
    lines = "\n".join(f'    "{name}"' for name in names)
    template = (ROOT / "mouse-keys.template.kbd").read_text()
    config = template.replace("@DEVICE_NAMES@", lines)
    rule_lines = ["# Generated by omarchy-mouse-keys/install.py for the selected keyboards."]
    for name in names:
        rule_lines.append(
            'SUBSYSTEM=="input", KERNEL=="event*", '
            'ENV{ID_INPUT_KEYBOARD}=="1", '
            f'ATTRS{{name}}=="{name}", TAG+="uaccess"'
        )
    return config, "\n".join(rule_lines) + "\n"


def refuse_different(target, content):
    if target.exists() and target.read_text() != content:
        raise RuntimeError(
            f"Existing file differs: {target}\n"
            "Compare and reconcile it before installing."
        )


def ensure_binary():
    if BINARY.is_file():
        version = subprocess.run(
            [str(BINARY), "--version"], capture_output=True, text=True, check=False
        )
        if version.returncode == 0 and version.stdout.strip() == f"kanata {VERSION}":
            return
    for command in ("git", "/usr/bin/cargo", "/usr/bin/rustc"):
        if not shutil.which(command):
            raise RuntimeError(f"Missing {command}; install git and Arch Rust first.")
    with tempfile.TemporaryDirectory(prefix="omarchy-mouse-keys-build-") as directory:
        source = Path(directory) / "kanata"
        run("git", "clone", "--depth", "1", "--branch", f"v{VERSION}",
            "https://github.com/jtroo/kanata.git", str(source))
        head = subprocess.check_output(
            ["git", "-C", str(source), "rev-parse", "HEAD"], text=True
        ).strip()
        if head != COMMIT:
            raise RuntimeError("The Kanata release tag differs from the pinned commit.")
        environment = os.environ.copy()
        environment["RUSTC"] = "/usr/bin/rustc"
        run("/usr/bin/cargo", "build", "--release", "--locked",
            "--no-default-features", "--bin", "kanata", cwd=source, env=environment)
        BINARY.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source / "target/release/kanata", BINARY)
        BINARY.chmod(0o755)


def privileged_command():
    command = "sudo" if sys.stdin.isatty() else "pkexec"
    if not shutil.which(command):
        raise RuntimeError(f"Missing {command} for the keyboard permission rule.")
    return command


def write_file(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    path.chmod(0o644)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--list", action="store_true", help="List available keyboard names")
    parser.add_argument("--device", action="append", default=[], metavar="NAME",
                        help="Exact keyboard name; repeat for multiple keyboards")
    parser.add_argument("--preview", metavar="DIR",
                        help="Render files into DIR without installing")
    args = parser.parse_args()

    devices = keyboard_devices()
    if args.list:
        for name, nodes in sorted(devices.items()):
            print(f"{name} ({', '.join(str(node) for node in nodes)})")
        return
    names = list(dict.fromkeys(args.device))
    if not names:
        parser.error("Choose a keyboard with --device NAME; use --list to see names.")
    config, rule = render(names)
    service = (ROOT / "kanata-mouse-keys.service").read_text()

    if args.preview:
        destination = Path(args.preview).expanduser().resolve()
        destination.mkdir(parents=True, exist_ok=True)
        write_file(destination / "mouse-keys.kbd", config)
        write_file(destination / RULE.name, rule)
        write_file(destination / SERVICE.name, service)
        print(f"Rendered to {destination}")
        return

    if not os.environ.get("XDG_RUNTIME_DIR") or os.geteuid() == 0:
        raise RuntimeError("Run as the desktop user in an active graphical session.")
    missing = set(names) - set(devices)
    if missing:
        raise RuntimeError(f"Keyboard not connected: {', '.join(sorted(missing))}")
    for target, content in ((CONFIG, config), (SERVICE, service), (RULE, rule)):
        refuse_different(target, content)

    ensure_binary()
    with tempfile.TemporaryDirectory(prefix="omarchy-mouse-keys-") as directory:
        candidate = Path(directory) / "mouse-keys.kbd"
        candidate.write_text(config)
        run(str(BINARY), "--check", "--cfg", str(candidate))
        run("systemd-analyze", "--user", "verify", str(ROOT / SERVICE.name))
        rule_candidate = Path(directory) / RULE.name
        rule_candidate.write_text(rule)

        privilege = privileged_command()
        write_file(CONFIG, config)
        write_file(SERVICE, service)
        run(privilege, "/usr/bin/install", "-Dm644", str(rule_candidate), str(RULE))
        run(privilege, "/usr/bin/udevadm", "control", "--reload-rules")
        username = pwd.getpwuid(os.getuid()).pw_name
        for name in names:
            for node in devices[name]:
                run(privilege, "/usr/bin/setfacl", "-m",
                    f"u:{username}:rw", str(node))
    run("systemctl", "--user", "daemon-reload")
    run("systemctl", "--user", "enable", SERVICE.stem)
    run("systemctl", "--user", "restart", SERVICE.stem)
    run("systemctl", "--user", "is-active", "--quiet", SERVICE.stem)
    print("Mouse keys installed and active. Test a physical keypress.")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"install failed: {error}", file=sys.stderr)
        sys.exit(1)
